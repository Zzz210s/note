LINK_RE = re.compile(r"\]\((?:<([^>]+)>|([^)\s]+))\)")


def leftover_links() -> list[str]:
    """改写后仍指向旧 MOC 的 markdown 链接(应为空)。"""
    out: list[str] = []
    for p in sorted(ROOT.rglob("*.md")):
        if any(part in (".git", "docs", ".superpowers") for part in p.parts):
            continue
        for m in LINK_RE.finditer(p.read_text(encoding="utf-8", errors="replace")):
            bare = (m.group(1) or m.group(2)).split("#")[0].strip()
            try:
                rel = (p.parent / bare).resolve().relative_to(ROOT).as_posix()
            except (ValueError, OSError):
                continue
            if rel in OLD_MOCS:
                out.append("%s -> %s" % (p.relative_to(ROOT).as_posix(), bare))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="改写旧 MOC 引用(Task 8)")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--dry-run", action="store_true", help="只检查命中,不写文件(默认行为)")
    args = ap.parse_args(argv)
    miss = 0
    for rel, old, new in RULES:
        p = ROOT / rel
        text = p.read_text(encoding="utf-8")
        if old not in text:
            if new in text:
                continue          # 已应用(幂等:重跑不报错)
            print("MISS %s | %s" % (rel, old[:70]))
            miss += 1
            continue
        if args.apply:
            p.write_text(text.replace(old, new), encoding="utf-8", newline="\n")
    print("规则 %d 条,未命中 %d 条%s" % (len(RULES), miss, "(dry-run)" if not args.apply else ""))
    left = leftover_links()
    if left:
        print("仍指向旧 MOC 的链接 %d 处:" % len(left))
        for line in left:
            print("   %s" % line)
    return 1 if (miss or left) else 0


